@pytest.mark.parametrize(("formula", "expected"), EXCEL, ids=[f for f, _ in EXCEL])
def test_matches_excel(formula, expected):
    got = formulas.evaluate("=" + formula, CONTEXT)
    if isinstance(expected, bool):
        assert got is expected
    elif isinstance(expected, (int, float)):
        assert isinstance(got, float) and math.isclose(got, expected, rel_tol=1e-9, abs_tol=1e-9), (
            got
        )
    else:
        assert got == expected
