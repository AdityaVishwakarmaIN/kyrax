def test_stress_onecell_everything():
    path = TESTDATA / "stress_onecell_everything.xlsx"
    sheet = read_excel_turbo(str(path)).load_sheet(0, features="all")
    rb = sheet.to_arrow()
    style_idx = sheet.style_indices()
    style_table = sheet.style_table()
    assert style_idx is not None and style_table is not None

    merges = sheet.merges()
    assert merges is not None
    assert any(m.replace("$", "").upper().startswith("B2") for m in merges)

    formulas = sheet.formulas()
    assert formulas is not None and formulas.num_rows >= 1
    fpd = formulas.to_pydict()
    # B2 → data row 0, col 1
    assert any(fpd["row"][i] == 0 and fpd["col"][i] == 1 for i in range(formulas.num_rows))

    comments = sheet.comments()
    assert comments is not None and comments.num_rows >= 1
    cpd = comments.to_pydict()
    assert any(r in cpd["ref"] for r in ("A2", "B2", "D2", "A4", "D4", "C4"))

    hlinks = sheet.hyperlinks()
    assert hlinks is not None and len(hlinks) >= 1
    refs_h = [h["ref"].split(":")[0] for h in hlinks]
    assert any(r in refs_h for r in ("A2", "B2", "D2", "C4"))

    wb = openpyxl.load_workbook(path, data_only=False)
    ws = wb.active

    for addr in ("A2", "D2", "A4", "D4", "C4"):
        cell = ws[addr]
        tr, tc = cell.row - 2, cell.column - 1
        tv = cell_value(rb, tr, tc)
        ov = cell.value
        # formula cells compared via formulas(); plain values here
        if not (isinstance(ov, str) and ov.startswith("=")):
            assert values_equal(tv, ov), f"{addr}: turbo={tv!r} oxl={ov!r}"
        xf = style_idx[tc][tr]
        rust = style_table[xf]
        assert rust["number_format"] == (cell.number_format or "General") or (
            cell.number_format not in (None, "General")
            and rust["number_format"] == cell.number_format
        ), f"{addr} fmt {rust['number_format']!r} vs {cell.number_format!r}"
        assert rust["font"]["bold"] is True
        assert rust["fill"]["pattern"] in ("solid", "none") or rust["fill"]["pattern"]

    # B2 formula text
    for i in range(formulas.num_rows):
        if fpd["row"][i] == 0 and fpd["col"][i] == 1:
            assert "1+2" in (fpd["text"][i] or "").replace(" ", "")
    wb.close()


