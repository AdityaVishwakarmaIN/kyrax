def test_stress_multisheet_by_name_and_index():
    path = TESTDATA / "stress_multisheet.xlsx"
    reader = read_excel_turbo(str(path))
    names = reader.sheet_names
    assert names == ["Values", "MergedLinks", "Comments", "Empty"]

    wb = openpyxl.load_workbook(path, data_only=True)
    wb_f = openpyxl.load_workbook(path, data_only=False)

    for idx, name in enumerate(names):
        by_i = reader.load_sheet(idx, features="all")
        by_n = reader.load_sheet(name, features="all")
        assert by_i.name == by_n.name == name
        assert by_i.nrows == by_n.nrows
        assert by_i.ncols == by_n.ncols

        ws = wb[name]
        ws_f = wb_f[name]

        if name == "Empty":
            # empty-but-valid: every accessor under features="all" must not panic
            rb = by_i.to_arrow()
            assert rb.num_rows == by_i.nrows == 0
            assert by_i.merges() is not None
            assert by_i.hyperlinks() is not None
            assert by_i.comments() is not None
            assert by_i.tables() is not None
            # style_table is workbook-level; may be present via features=all
            st = by_i.style_table()
            assert st is not None or st is None  # must not raise
            # style_indices may be None when ncols==0 (no columns to index)
            _ = by_i.style_indices()
            f = by_i.formulas()
            if f is not None:
                assert f.num_rows == 0
            c = by_i.comments()
            assert c is not None and c.num_rows == 0
            assert isinstance(by_i.merges(), list)
            assert isinstance(by_i.hyperlinks(), list)
            assert isinstance(by_i.tables(), list)
            continue

        rb = by_i.to_arrow()
        # sample values
        for orow in range(2, min((ws.max_row or 1), 20) + 1):
            for ocol in range(1, min((ws.max_column or 1), 5) + 1):
                ov = ws.cell(orow, ocol).value
                tr, tc = orow - 2, ocol - 1
                if tr >= by_i.nrows or tc >= by_i.ncols:
                    if ov is not None:
                        pytest.fail(f"{name}: turbo oob for {orow},{ocol} val={ov}")
                    continue
                tv = cell_value(rb, tr, tc)
                assert values_equal(tv, ov), f"{name} ({orow},{ocol}): turbo={tv!r} oxl={ov!r}"

        if name == "MergedLinks":
            merges = by_i.merges()
            assert merges is not None
            oxl_m = set(str(r) for r in ws_f.merged_cells.ranges)
            assert set(merges) == oxl_m, f"merges {set(merges)!r} vs {oxl_m!r}"
            hlinks = by_i.hyperlinks()
            assert hlinks is not None and len(hlinks) >= 1
            # at least one external link to example.com
            targets = [h.get("target") or "" for h in hlinks]
            assert any("example.com" in t for t in targets), targets

        if name == "Comments":
            comments = by_i.comments()
            assert comments is not None and comments.num_rows >= 3
            cpd = comments.to_pydict()
            refs = set(cpd["ref"])
            assert "A2" in refs and "B5" in refs
            tables = by_i.tables()
            assert tables is not None
            assert any(t["name"] == "TblComments" for t in tables)

        if name == "Values":
            tables = by_i.tables()
            assert tables is not None
            assert any(t["name"] == "TblValues" for t in tables)
            assert by_i.nrows == 100
            assert by_i.ncols == 5

    # Defined names: sheet-scoped resolve to correct sheet indices
    # Re-load any sheet with defined_names flag
    _ = reader.load_sheet(0, features="all")
    dns = reader.defined_names()
    assert dns is not None
    scoped = [d for d in dns if d.get("scope") is not None]
    # Expect sheet-scoped names on sheets 2 (idx 1) and 4 (idx 3)
    scopes = {int(d["scope"]) for d in scoped}
    # At least one name scoped to sheet index 1 or 3
    assert scopes & {1, 3} or any(
        "Sheet2" in (d.get("name") or "") or "Empty" in (d.get("name") or "") or "Local" in (d.get("name") or "")
        for d in dns
    ), f"expected sheet-scoped names, got {dns}"

    # If scope present, verify index matches openpyxl localSheetId
    for d in scoped:
        sc = int(d["scope"])
        assert 0 <= sc < len(names), f"scope {sc} out of range for {d}"

    wb.close()
    wb_f.close()


