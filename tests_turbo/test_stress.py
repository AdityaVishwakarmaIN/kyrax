def test_stress_types():
    path = TESTDATA / "stress_types.xlsx"
    sheet = read_excel_turbo(str(path)).load_sheet(0, features="all")
    rb = sheet.to_arrow()

    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb.active
    wb_f = openpyxl.load_workbook(path, data_only=False)
    ws_f = wb_f.active

    # Native Arrow booleans (BooleanArray), not Float64 0/1 — assert explicitly.
    bool_col = 0
    assert rb.column(bool_col).type == "bool", (
        f"expected native Arrow bool, got {rb.column(bool_col).type}"
    )
    for orow in range(2, 6):
        ov = ws.cell(orow, 1).value
        if ov is None:
            continue
        tr = orow - 2
        tv = cell_value(rb, tr, 0)
        assert isinstance(ov, bool)
        assert tv is True if ov else tv is False, f"bool at row {orow}: expected {ov}, got {tv!r}"
        assert values_equal(tv, ov), f"bool map row {orow}: {tv} vs {ov}"

    # Unicode / entities / empty / long
    checks = [
        (2, 2, "emoji"),  # contains emoji marker
        (2, 3, "&"),  # entities
        (3, 3, "<"),
    ]
    for orow, ocol, needle in checks:
        tr, tc = orow - 2, ocol - 1
        tv = cell_value(rb, tr, tc)
        ov = ws.cell(orow, ocol).value
        assert values_equal(tv, ov), f"({orow},{ocol}) turbo={tv!r} oxl={ov!r}"
        if isinstance(tv, str):
            assert needle in tv or needle in (ov or "")

    # empty string: turbo may yield "" or None depending on storage
    tv_empty = cell_value(rb, 0, 3)  # D2
    ov_empty = ws.cell(2, 4).value
    assert ov_empty in ("", None) or ov_empty == ""
    assert tv_empty in ("", None), f"empty str: {tv_empty!r}"

    # long string 32k
    tv_long = cell_value(rb, 0, 4)
    ov_long = ws.cell(2, 5).value
    assert isinstance(tv_long, str) and len(tv_long) == len(ov_long) == 32000

    # floats
    for orow in (2, 3, 4, 5):
        ov = ws.cell(orow, 6).value
        if ov is None:
            continue
        tv = cell_value(rb, orow - 2, 5)
        assert values_equal(tv, ov, rel=1e-9), f"float row {orow}: {tv} vs {ov}"

    # date edge serials
    for orow in (2, 3, 4):
        ov = ws.cell(orow, 7).value
        tv = cell_value(rb, orow - 2, 6)
        if ov is None and tv is None:
            continue
        assert values_equal(tv, ov), f"date row {orow}: {tv} vs {ov}"

    # formula with entities / quoted comma
    formulas = sheet.formulas()
    assert formulas is not None and formulas.num_rows >= 1
    fpd = formulas.to_pydict()
    texts = fpd["text"]
    assert any("," in (t or "") or "&" in (t or "") for t in texts), texts

    wb.close()
    wb_f.close()


