def test_stress_sparse_coordinates():
    """Every non-empty cell lands at the SAME (row, col) as openpyxl."""
    path = TESTDATA / "stress_sparse.xlsx"
    sheet = read_excel_turbo(str(path)).load_sheet(0, features="all")
    rb = sheet.to_arrow()
    style_idx = sheet.style_indices()
    style_table = sheet.style_table()
    assert style_idx is not None and style_table is not None

    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb.active

    mismatches = []
    null_mismatches = []
    style_mismatches = []
    checked_nonzero = 0

    # Determine shared max extent
    max_r = max(sheet.nrows + 1, ws.max_row or 1)  # sheet row
    max_c = max(sheet.ncols, ws.max_column or 1)

    # Turbo must cover at least openpyxl's used range for data rows
    # (header excluded): data rows = sheet rows 2..max_row
    assert sheet.ncols >= 1

    for orow in range(2, (ws.max_row or 1) + 1):
        for ocol in range(1, (ws.max_column or 1) + 1):
            ov = ws.cell(orow, ocol).value
            tr = orow - 2
            tc = ocol - 1
            if tr < 0:
                continue
            if tr >= sheet.nrows or tc >= sheet.ncols:
                if ov is not None:
                    mismatches.append(
                        ("oob", orow, ocol, ov, f"turbo nrows={sheet.nrows} ncols={sheet.ncols}")
                    )
                continue
            tv = cell_value(rb, tr, tc)
            if ov is None:
                if tv is not None:
                    null_mismatches.append((orow, ocol, tv))
                    if len(null_mismatches) >= 12:
                        break
                continue
            if not values_equal(tv, ov):
                mismatches.append((orow, ocol, tv, ov))
                if len(mismatches) >= 12:
                    break
                continue
            checked_nonzero += 1
            # number_format via style index
            xf = style_idx[tc][tr]
            rust_fmt = style_table[xf]["number_format"]
            oxl_fmt = ws.cell(orow, ocol).number_format or "General"
            if rust_fmt != oxl_fmt and not (
                rust_fmt in ("General", "general") and oxl_fmt in ("General", "general")
            ):
                if oxl_fmt not in ("General", "general"):
                    style_mismatches.append((orow, ocol, rust_fmt, oxl_fmt))
        if len(mismatches) >= 12 or len(null_mismatches) >= 12:
            break

    wb.close()

    # Hard-coded sparse patterns from gen_stress
    # A10=100, C10=300 (no B10); D15=400; A20=1, C20 formula
    hard = []
    wb2 = openpyxl.load_workbook(path, data_only=False)
    ws2 = wb2.active
    for addr, exp_col_letter in [("A10", "A"), ("C10", "C"), ("D15", "D"), ("A20", "A")]:
        cell = ws2[addr]
        orow, ocol = cell.row, cell.column
        tr, tc = orow - 2, ocol - 1
        tv = cell_value(rb, tr, tc)
        if cell.value is not None and not isinstance(cell.value, str):
            if not values_equal(tv, cell.value):
                hard.append((addr, tv, cell.value, tr, tc))
        # ensure coordinate letter matches
        if get_column_letter(tc + 1) != exp_col_letter:
            hard.append((addr, "col_letter", get_column_letter(tc + 1), exp_col_letter))
    # B10 must be null while A10 and C10 set
    tr, tc = 10 - 2, 2 - 1  # B10
    if tr < sheet.nrows and cell_value(rb, tr, tc) is not None:
        # only if openpyxl also has None
        if ws2["B10"].value is None:
            hard.append(("B10", "expected null", cell_value(rb, tr, tc)))
    # formula at C20
    formulas = sheet.formulas()
    assert formulas is not None
    fpd = formulas.to_pydict()
    found_c20 = False
    for i in range(formulas.num_rows):
        if fpd["row"][i] == 20 - 2 and fpd["col"][i] == 3 - 1:
            found_c20 = True
            assert "A20" in (fpd["text"][i] or "")
    if not found_c20:
        hard.append(("C20 formula missing at (18, 2)", fpd["row"][:5], fpd["col"][:5]))
    wb2.close()

    assert checked_nonzero > 100, f"too few non-empty cells checked: {checked_nonzero}"
    assert not hard, f"hard sparse patterns failed: {hard}"
    assert not mismatches, f"value mismatches e.g. {mismatches[:8]}"
    assert not null_mismatches, f"null mismatches e.g. {null_mismatches[:8]}"
    assert not style_mismatches, f"number_format mismatches e.g. {style_mismatches[:8]}"


